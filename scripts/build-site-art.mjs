// npm run art:site — regenerate lib/siteArt.js
//
// WHY THIS EXISTS: /public/cats/ is gitignored (20,000 cats is ~340MB), so most
// of what is on this machine never reaches Vercel. A site that renders
// /cats/<id>.webp straight from lib/catPool.json looks perfect in dev and ships
// a wall of broken images to production.
//
// So the site never reads catPool.json. It reads lib/siteArt.js, which this
// script builds from the INTERSECTION of "exists on disk" and "tracked by git".
// If a cat is not in the index, it cannot appear on the site.
//
// Re-run this after `git add`ing more cats.

import { execSync } from "node:child_process";
import { existsSync, writeFileSync, readdirSync } from "node:fs";

const tracked = new Set(
  execSync("git ls-files public/cats public/art", { encoding: "utf8" })
    .trim()
    .split("\n")
    .filter(Boolean)
);

// cats: tracked AND on disk
const cats = [...tracked]
  .filter((p) => p.startsWith("public/cats/") && existsSync(p))
  .map((p) => p.replace(/^public/, ""))
  .sort((a, b) => {
    const n = (s) => parseInt(s.match(/(\d+)/)?.[1] ?? "0", 10);
    return n(a) - n(b);
  });

// the transparent hero-grade art
const art = [...tracked]
  .filter((p) => /^public\/art\/[^/]+\.(avif|webp|png)$/i.test(p) && existsSync(p))
  .map((p) => p.replace(/^public/, ""))
  .sort();

const community = [...tracked]
  .filter((p) => /^public\/art\/x\//i.test(p) && existsSync(p))
  .map((p) => p.replace(/^public/, ""))
  .sort();

const onDisk = existsSync("public/cats") ? readdirSync("public/cats").length : 0;

const out = `// GENERATED by scripts/build-site-art.mjs — do not edit by hand.
// Run \`npm run art:site\` to rebuild.
//
// Every path here is BOTH on disk AND tracked by git, so everything in this
// file survives a deploy. /public/cats/ is gitignored, so the machine that
// generated this had ${onDisk} cats locally and only ${cats.length} of them ship.

/** Tracked cat portraits, safe to render anywhere. */
export const CATS = ${JSON.stringify(cats, null, 2)};

/** The transparent, hero-grade tubby art. */
export const ART = ${JSON.stringify(art, null, 2)};

/** Community pieces pulled from the official X. */
export const COMMUNITY = ${JSON.stringify(community, null, 2)};

/**
 * Deterministic pick of \`n\` items — same output on server and client, so it
 * never causes a hydration mismatch. \`seed\` just offsets the walk.
 */
export function pick(list, n, seed = 0) {
  if (!list.length) return [];
  const out = [];
  // a coprime-ish stride spreads the picks across the list instead of taking a
  // contiguous run, which would look like one batch of very similar cats
  const stride = 97;
  for (let i = 0; i < n; i++) {
    out.push(list[(seed + i * stride) % list.length]);
  }
  return out;
}
`;

writeFileSync("lib/siteArt.js", out);
console.log(
  `lib/siteArt.js — ${cats.length} cats, ${art.length} art, ${community.length} community` +
    (onDisk > cats.length ? `  (${onDisk - cats.length} local cats excluded: not in git)` : "")
);
